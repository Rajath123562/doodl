import { test, expect } from '@playwright/test';

test.describe('Real 2-Browser Multiplayer Match Verification (P0-001, P0-002, P0-003, P0-008, P0-010, P0-011, P0-012, P0-013, P0-019)', () => {
  test('two independent browser sessions join same invite, draw and guess in real time', async ({
    browser,
  }) => {
    // 1. Create two completely independent browser contexts (simulating two real users on separate devices)
    const hostContext = await browser.newContext({
      viewport: { width: 1280, height: 800 },
    });
    const guestContext = await browser.newContext({
      viewport: { width: 390, height: 844 }, // Mobile device viewport for Guest (P0-019)
      isMobile: true,
      hasTouch: true,
    });

    const hostPage = await hostContext.newPage();
    const guestPage = await guestContext.newPage();

    // 2. Host navigates to landing page and enters nickname (P0-001)
    await hostPage.goto('/');
    await expect(hostPage.locator('h1')).toContainText('Draw, guess, and');

    const hostNicknameInput = hostPage.locator('input[placeholder="Enter nickname..."]');
    await hostNicknameInput.fill('AliceHost');

    // Host clicks Create Private Room (P0-002)
    const createBtn = hostPage.getByRole('button', { name: 'Create Private Room' });
    await createBtn.click();

    // Host arrives at Lobby
    await expect(hostPage.getByRole('heading', { name: 'Game Lobby' })).toBeVisible({ timeout: 10000 });

    // Extract the authoritative room code generated by server
    const roomCodeElement = hostPage.locator('.font-head.font-extrabold.text-4xl.tracking-wider');
    await expect(roomCodeElement).toBeVisible();
    const roomCode = (await roomCodeElement.textContent())?.trim();
    expect(roomCode).toBeTruthy();
    expect(roomCode!.length).toBeGreaterThanOrEqual(4);

    // Host sees 1 player connected initially
    await expect(hostPage.getByRole('main').getByText('AliceHost')).toBeVisible();
    await expect(hostPage.getByText('Need at least 2 connected players to start.')).toBeVisible();

    // 3. Guest joins via room code (P0-003)
    await guestPage.goto('/');
    const guestNicknameInput = guestPage.locator('input[placeholder="Enter nickname..."]');
    await guestNicknameInput.fill('BobGuesser');

    const joinCodeInput = guestPage.locator('input[placeholder="ROOM CODE"]');
    await joinCodeInput.fill(roomCode!);

    const joinBtn = guestPage.getByRole('button', { name: 'Join Room' });
    await joinBtn.click();

    // Guest arrives in same lobby
    await expect(guestPage.getByRole('heading', { name: 'Game Lobby' })).toBeVisible({ timeout: 10000 });

    // 4. Verify both sessions see each other in real connected seats (P0-003)
    // Host sees Bob in the roster
    await expect(hostPage.getByRole('main').getByText('BobGuesser')).toBeVisible({ timeout: 5000 });
    await expect(hostPage.getByText('Connected Players (2 /')).toBeVisible();
    await expect(hostPage.getByText('✓ Ready to play!')).toBeVisible();

    // Guest sees Alice in the roster
    await expect(guestPage.getByRole('main').getByText('AliceHost')).toBeVisible({ timeout: 5000 });
    await expect(guestPage.getByText('Waiting for the host to start the game...')).toBeVisible();

    // 5. Host starts game (P0-005, P0-006)
    const startBtn = hostPage.getByRole('button', { name: 'Start Game ▶' });
    await startBtn.click();

    // 6. Host (drawer) receives Word Choice modal with 3 candidates (P0-008)
    const wordChoiceHeading = hostPage.getByRole('heading', { name: 'Choose Your Word!' });
    await expect(wordChoiceHeading).toBeVisible({ timeout: 10000 });

    // Guest must NEVER receive word choice overlay (P0-008 Secrecy)
    await expect(guestPage.getByRole('heading', { name: 'Choose Your Word!' })).not.toBeVisible();

    // Host picks the first candidate word
    const candidateButtons = hostPage.locator('.grid button');
    await expect(candidateButtons).toHaveCount(3);
    const chosenWord = (await candidateButtons.first().textContent())?.trim();
    expect(chosenWord).toBeTruthy();

    await candidateButtons.first().click();

    // 7. Transition to DRAWING phase (P0-010, P0-011)
    // Host HUD displays secret word
    const hostHUD = hostPage.locator('.font-mono.text-2xl');
    await expect(hostHUD).toContainText(chosenWord!, { timeout: 10000 });

    // Guest HUD displays masked word (never plaintext word!)
    const guestHUD = guestPage.locator('.font-mono.text-2xl');
    await expect(guestHUD).toBeVisible({ timeout: 10000 });
    const guestMasked = await guestHUD.textContent();
    expect(guestMasked).not.toContain(chosenWord!);
    expect(guestMasked).toContain('_');

    // 8. Host draws on canvas with mouse pointer (P0-010, P0-011)
    const hostCanvas = hostPage.locator('canvas');
    await expect(hostCanvas).toBeVisible();
    const box = await hostCanvas.boundingBox();
    expect(box).toBeTruthy();

    if (box) {
      // Draw a line across the canvas
      await hostPage.mouse.move(box.x + 50, box.y + 50);
      await hostPage.mouse.down();
      await hostPage.mouse.move(box.x + 150, box.y + 150, { steps: 5 });
      await hostPage.mouse.move(box.x + 250, box.y + 100, { steps: 5 });
      await hostPage.mouse.up();
    }

    // 9. Guest submits guess (P0-012, P0-013)
    const guestChatInput = guestPage.locator('input[placeholder="Type your guess here..."]');
    await expect(guestChatInput).toBeVisible();

    // Wrong guess first
    await guestChatInput.fill('RandomIncorrectWord');
    await guestPage.getByRole('button', { name: 'Send' }).click();
    await expect(guestPage.getByText('RandomIncorrectWord')).toBeVisible({ timeout: 5000 });

    // Correct guess!
    await guestChatInput.fill(chosenWord!);
    await guestPage.getByRole('button', { name: 'Send' }).click();

    // 10. Verify scoring and public announcement (P0-012, P0-013)
    // Guest input switches to already guessed confirmation
    await expect(
      guestPage.locator('input[placeholder*="guessed"]')
    ).toBeVisible({ timeout: 5000 });

    // Host sees public correct announcement
    await expect(hostPage.getByText('BobGuesser guessed the word!')).toBeVisible({ timeout: 5000 });

    // Both players see guess status and points updated
    await expect(hostPage.getByText('✓ Guessed!')).toBeVisible({ timeout: 5000 });
    await expect(hostPage.locator('.font-head.font-extrabold.text-xs').filter({ hasText: 'pts' }).first()).toBeVisible();

    // Cleanup contexts
    await hostContext.close();
    await guestContext.close();
  });
});
